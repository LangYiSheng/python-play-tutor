def window_fingerprint() -> str:
    """改提示词或窗口规则必须让幂等键失效。"""
    return hashlib.sha256((WINDOW_SYSTEM + WINDOW_TEMPLATE + WINDOW_VERSION).encode("utf-8")).hexdigest()[:16]
