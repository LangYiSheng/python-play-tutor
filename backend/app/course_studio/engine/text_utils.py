"""Pure stdlib text normalization, JSON extraction, and page-range helpers."""

from __future__ import annotations

import json
import re
from collections.abc import Sequence
from typing import Any

PAUSE_MARK = "[停顿]"

_PAUSE_RE = re.compile(r"\[\s*(?:停顿|pause)\s*\]", re.IGNORECASE)
_PAUSE_VARIANTS = re.compile(
    r"\[\s*(?:pause|停顿)\s*\]|【\s*(?:pause|停顿)\s*】|[(（]\s*(?:pause|停顿)\s*[)）]",
    re.IGNORECASE,
)
_DUP_PAUSE = re.compile(r"(?:\[停顿\]\s*){2,}")
_OPENING_LINE = re.compile(r"^(大家好|这节课|今天)[，,、].{0,20}$", re.MULTILINE)
_SCRIPT_LABEL_LINE = re.compile(
    r"^[\[【(（]\s*(?:slide\s*\d+|第?\s*\d+\s*页)[^\]】)）]*[\]】)）]\s*$",
    re.IGNORECASE,
)
_SCRIPT_LABEL_PREFIX = re.compile(
    r"^[\[【(（]?\s*(?:slide\s*\d+|第?\s*\d+\s*页)\s*[\]】)）]?\s*[-—–－:：]\s*",
    re.IGNORECASE,
)
_FENCE_RE = re.compile(r"^```[a-zA-Z]*\s*|\s*```$")
_SQUEEZE_RE = re.compile(r"[\s，,。.；;：:、！!？?（）()《》“”\"'‘’\-—·]+")


def squeeze_text(text: str) -> str:
    """Normalize text for fuzzy comparison by removing punctuation and whitespace."""
    return _SQUEEZE_RE.sub("", text or "").lower()


def strip_pause_marks(text: str) -> str:
    """Remove pause markers and tidy residual whitespace."""
    t = _PAUSE_RE.sub("", text or "")
    t = re.sub(r"[ \t]{2,}", " ", t)
    t = re.sub(r" *\n *", "\n", t)
    t = re.sub(r"\n{3,}", "\n\n", t)
    return t.strip()


def normalize_pause_marks(text: str) -> str:
    """Canonicalize pause marker variants to [停顿] and collapse duplicates."""
    t = _PAUSE_VARIANTS.sub(PAUSE_MARK, text or "")
    return _DUP_PAUSE.sub(PAUSE_MARK, t)


def clean_note(text: str) -> str:
    """Strip leftover Markdown markers and banned opening phrases."""
    t = (text or "").strip()
    t = re.sub(r"^```[a-zA-Z]*\s*", "", t)
    t = re.sub(r"\s*```$", "", t)
    t = re.sub(r"^#{1,6}\s*", "", t, flags=re.MULTILINE)
    t = re.sub(r"^\s*[-*+]\s+", "", t, flags=re.MULTILINE)
    t = re.sub(r"\*\*(.+?)\*\*", r"\1", t)
    t = re.sub(r"__(.+?)__", r"\1", t)
    t = _OPENING_LINE.sub("", t)
    t = re.sub(r"\n{3,}", "\n\n", t)
    return t.strip()


def strip_script_labels(text: str) -> str:
    """Remove accidental slide/page label prefixes generated by models."""
    out: list[str] = []
    for line in (text or "").splitlines():
        if _SCRIPT_LABEL_LINE.match(line):
            continue
        stripped = _SCRIPT_LABEL_PREFIX.sub("", line).strip()
        if not stripped and line.strip():
            continue
        out.append(stripped)
    return "\n".join(out)


def clean_script(text: str) -> str:
    """Sanitize oral narration script text while preserving canonical pause marks."""
    t = clean_note(text)
    t = strip_script_labels(t)
    t = normalize_pause_marks(t)
    t = re.sub(r"\n{3,}", "\n\n", t)
    return t.strip()


def parse_page_spec(spec: str) -> set[int]:
    """Parse page range specs such as '1-3, 5' into integer page numbers."""
    keep: set[int] = set()
    for part in (spec or "").split(","):
        part = part.strip()
        if not part:
            continue
        if "-" in part:
            a, b = part.split("-", 1)
            keep.update(range(int(a), int(b) + 1))
        else:
            keep.add(int(part))
    return keep


def format_page_ranges(pages: Sequence[int], *, sep: str = ", ", dash: str = "-") -> str:
    """Format sorted positive integers into compact ranges (e.g. [1,2,3,5] -> '1-3, 5')."""
    nums = sorted({int(p) for p in pages if int(p) > 0})
    out: list[str] = []
    i = 0
    while i < len(nums):
        j = i
        while j + 1 < len(nums) and nums[j + 1] == nums[j] + 1:
            j += 1
        out.append(str(nums[i]) if i == j else f"{nums[i]}{dash}{nums[j]}")
        i = j + 1
    return sep.join(out)


def extract_json_payload(text: str) -> Any:
    """Extract and decode the JSON object or array from an LLM reply."""
    body = _FENCE_RE.sub("", (text or "").strip()).strip()
    if not body:
        raise ValueError("回复里没有 JSON")
    try:
        return json.loads(body)
    except ValueError:
        pass
    candidates: list[tuple[int, int]] = []
    obj_start, obj_end = body.find("{"), body.rfind("}")
    if obj_start >= 0 and obj_end > obj_start:
        candidates.append((obj_start, obj_end))
    arr_start, arr_end = body.find("["), body.rfind("]")
    if arr_start >= 0 and arr_end > arr_start:
        candidates.append((arr_start, arr_end))
    candidates.sort(key=lambda pair: pair[0])
    for start, end in candidates:
        try:
            return json.loads(body[start : end + 1])
        except ValueError:
            continue
    raise ValueError("回复里没有合法 JSON")
